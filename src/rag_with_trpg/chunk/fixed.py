# │  C1  │ 커버리지           │ `overlap=0` 이면 `"".join(c.text) ==      │ 기존 유지                       │
# │      │                  │ text`                                    │                              │
# ├──────┼──────────────────┼──────────────────────────────────────────┼──────────────────────────────┤
# │ C1'  │ 커버리지 (일반)     │ `starts[0]==0`, `ends[-1]==len(text)`,    │ 신설. overlap>0 에서도 검증     │
# │      │                  │ 모든 `i` 에서 `starts[i+1] <= ends[i]`     │ 가능해진다                      │
