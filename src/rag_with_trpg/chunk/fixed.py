def fixed(
    text: str,
    size: int,
    overlap: int = 0,
    min_chunk: int = 0,
    *,
    doc_id: str | None = None,  # PageEntry.slug — provenance (D-35 · D-07)
) -> list[Chunk]:
    """고정 길이 슬라이딩 윈도우. 계약 C1~C7.

    마지막 창은 start = max(0, len(text) - size) 로 되감아 꼬리를 흡수한다.
    그 결과 마지막 한 쌍의 겹침은 overlap 보다 커질 수 있다 (C3 이 부등식인 이유).
    """


def chunk_old(text: str, size: int, overlap: int = 0, min_chunk: int = 0) -> list[str]:
    # 1. 입력 가드: size <= 0 / overlap < 0 / overlap >= size -> ValueError
    # 2. 짧은 입력 즉시 반환: len(text) <= size -> 청크 1개 (빈 문자열이면 [])
    # 3. stride = size - overlap
    # 4. i = 0 에서 시작해 while i < len(text):
    #       끝을 넘기면(= i + size >= len(text)) 마지막 창이다:
    #           start = max(0, len(text) - size)   <- 뒤로 물러나 붙인다 (꼬리 흡수)
    #           마지막 창 방출 후 break
    #       아니면 text[i : i+size] 방출, i += stride
    # 5. 방출은 항상 (start, end) 오프셋과 함께 -> Chunk 로 감싼다  (§4)
    #
    # 함정: while j < times 같은 반복 횟수 계산으로 돌지 않는다.
    #       종료 조건을 위치(i)로 두면 계약이 위치로 검증된다
    if overlap >= size:
        raise ValueError("Overlap must be less than size")

    chunk_size: int = size - overlap
    text_length: int = len(text)
    result: list[str] = []
    times: int = text_length // chunk_size + 1
    i, j, c = 0, 0, 0

    while j < times:
        c = min(i + size, text_length)
        sentence = text[i:c]

        if len(sentence) > 0:
            result.append(sentence)

        i = i + chunk_size
        j += 1

    return result
